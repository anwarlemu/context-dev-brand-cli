import type { Illustration } from '../illustrate/render.js';

// What `figma push` hands the Figma MCP tools. An illustration becomes a use_figma script that draws real ellipses
// in a named frame, one child frame per layer (field, hollow, filled), each paint bound to the brand color variable
// when the file has it (`figma tokens` first). Pictures and SVGs go through upload_assets (SVG arrives as editable
// vectors); HTML goes through html_to_figma.

const SCRIPT_LIMIT = 45000;
const b36 = (n: number) => n.toString(36);

type EncodedLayer = { id: string; kind: 'fill' | 'ring'; color: [number, number, number]; token?: string; opacity: number; stroke?: number; r?: number; cells?: string; raw?: number[] };

const rgb01 = (hex: string): [number, number, number] => {
	const n = Number.parseInt(hex.replace('#', '').slice(0, 6), 16);
	return [((n >> 16) & 255) / 255, ((n >> 8) & 255) / 255, (n & 255) / 255].map((v) => Math.round(v * 10000) / 10000) as [number, number, number];
};

/** A layer's circles as compactly as they allow: grid cell runs (base 36) when every dot sits on the lattice. */
function encode(ill: Illustration, l: Illustration['layers'][number], circles: number[]): EncodedLayer {
	const base: EncodedLayer = { id: l.id, kind: l.kind, color: rgb01(l.color), ...(l.token ? { token: l.token } : {}), opacity: l.opacity, ...(l.stroke ? { stroke: l.stroke } : {}) };
	const radii = new Set<number>();
	for (let i = 2; i < circles.length; i += 3) radii.add(circles[i]!);
	const g = ill.grid;
	if (g && radii.size <= 1) {
		const cols = Math.round((ill.width - 2 * g.ox) / g.pitch);
		const cells: number[] = [];
		let ok = true;
		for (let i = 0; i < circles.length && ok; i += 3) {
			const q = (circles[i]! - g.ox) / g.pitch - 0.5;
			const r = (circles[i + 1]! - g.oy) / g.pitch - 0.5;
			if (Math.abs(q - Math.round(q)) > 0.02 || Math.abs(r - Math.round(r)) > 0.02) ok = false;
			cells.push(Math.round(r) * cols + Math.round(q));
		}
		if (ok) {
			cells.sort((a, b) => a - b);
			const runs: string[] = [];
			for (let i = 0; i < cells.length; i++) {
				let j = i;
				while (j + 1 < cells.length && cells[j + 1] === cells[j]! + 1) j++;
				runs.push(j > i ? `${b36(cells[i]!)}+${b36(j - i)}` : b36(cells[i]!));
				i = j;
			}
			return { ...base, r: [...radii][0] ?? 0, cells: runs.join(',') };
		}
	}
	return { ...base, raw: circles.map((v) => Math.round(v * 100) / 100) };
}

/** use_figma scripts that draw the illustration; several when it is too big for one call, each safe to rerun. */
export function illustrationScripts(ill: Illustration, frameName: string): string[] {
	const parts: EncodedLayer[][] = [];
	let current: EncodedLayer[] = [];
	let size = 0;
	for (const l of ill.layers) {
		if (!l.circles.length) continue;
		// Split a layer into slices when its encoding alone would pass the limit.
		const per = Math.max(30, Math.floor(l.circles.length / 3 / Math.ceil(JSON.stringify(encode(ill, l, l.circles)).length / (SCRIPT_LIMIT - 6000))));
		for (let i = 0; i < l.circles.length; i += per * 3) {
			const e = encode(ill, l, l.circles.slice(i, i + per * 3));
			const n = JSON.stringify(e).length;
			if (size + n > SCRIPT_LIMIT - 6000 && current.length) {
				parts.push(current);
				current = [];
				size = 0;
			}
			current.push(e);
			size += n;
		}
	}
	if (current.length || !parts.length) parts.push(current);
	const g = ill.grid;
	const cols = g ? Math.round((ill.width - 2 * g.ox) / g.pitch) : 0;
	return parts.map((layers, index) => `// Draws ${frameName} (part ${index + 1} of ${parts.length}) as real ellipses. Generated by figma push; safe to rerun.
const FRAME = ${JSON.stringify(frameName)};
const W = ${ill.width}, H = ${ill.height};
const BG = ${ill.background ? JSON.stringify({ color: rgb01(ill.background), token: ill.backgroundToken }) : 'null'};
const GRID = ${g ? JSON.stringify({ ox: g.ox, oy: g.oy, pitch: g.pitch, cols }) : 'null'};
const LAYERS = ${JSON.stringify(layers)};
const PART = ${index}, FIRST = ${index === 0};
const vars = await figma.variables.getLocalVariablesAsync('COLOR');
const byToken = (t) => t && vars.find((v) => v.name === 'color/' + t);
const paint = (color, token) => {
  const p = { type: 'SOLID', color: { r: color[0], g: color[1], b: color[2] } };
  const v = byToken(token);
  return v ? figma.variables.setBoundVariableForPaint(p, 'color', v) : p;
};
let frame = figma.currentPage.children.find((n) => n.type === 'FRAME' && n.name === FRAME);
if (frame && FIRST) { frame.remove(); frame = undefined; }
if (!frame) {
  frame = figma.createFrame();
  frame.name = FRAME;
  frame.resize(W, H);
  const right = figma.currentPage.children.filter((n) => n !== frame).reduce((m, n) => Math.max(m, n.x + n.width), 0);
  frame.x = right ? right + 120 : 0;
  frame.y = 0;
  frame.clipsContent = true;
  frame.fills = BG ? [paint(BG.color, BG.token)] : [];
}
const created = [];
for (const L of LAYERS) {
  let group = frame.children.find((n) => n.name === L.id);
  if (!group) {
    group = figma.createFrame();
    group.name = L.id;
    group.resize(W, H);
    group.fills = [];
    group.clipsContent = false;
    group.opacity = L.opacity;
    frame.appendChild(group);
    group.x = 0; group.y = 0;
  }
  const fill = paint(L.color, L.token);
  const circles = [];
  if (L.cells) {
    for (const run of L.cells.split(',')) {
      const [a, n] = run.split('+');
      const start = parseInt(a, 36), len = n ? parseInt(n, 36) : 0;
      for (let k = start; k <= start + len; k++) circles.push([GRID.ox + ((k % GRID.cols) + 0.5) * GRID.pitch, GRID.oy + (Math.floor(k / GRID.cols) + 0.5) * GRID.pitch, L.r]);
    }
  } else for (let i = 0; i < L.raw.length; i += 3) circles.push([L.raw[i], L.raw[i + 1], L.raw[i + 2]]);
  for (const [x, y, r] of circles) {
    const e = figma.createEllipse();
    e.resize(r * 2, r * 2);
    e.x = x - r; e.y = y - r;
    if (L.kind === 'ring') { e.fills = []; e.strokes = [fill]; e.strokeWeight = L.stroke; e.strokeAlign = 'CENTER'; }
    else { e.fills = [fill]; e.strokes = []; }
    group.appendChild(e);
  }
  created.push({ layer: L.id, count: circles.length, groupId: group.id });
}
// Layers stay in drawing order: field under hollow under filled.
const order = ['field', 'hollow', 'filled'];
[...frame.children].sort((a, b) => order.indexOf(a.name) - order.indexOf(b.name)).forEach((n, i) => frame.insertChild(i, n));
return { frameId: frame.id, part: PART + 1, layers: created, createdNodeIds: [frame.id, ...created.map((c) => c.groupId)], mutatedNodeIds: [] };
`);
}

/** A use_figma script that imports a small SVG as editable layers in a named frame (the SVG's ids become layer names). */
export function svgScript(svg: string, frameName: string): string | null {
	const script = `// Imports ${frameName} as editable layers. Generated by figma push; safe to rerun.
const SVG = ${JSON.stringify(svg)};
// Text in the SVG imports as text layers only when its fonts are loaded first.
const FONTS = ${JSON.stringify([...new Set([...svg.matchAll(/font-family="([^"]+)"/g)].map((m) => m[1]!.split(',')[0]!.replace(/['"]/g, '').trim()))])};
const missing = [];
for (const family of FONTS) { try { await figma.loadFontAsync({ family, style: 'Regular' }); } catch (e) { missing.push(family); } }
const old = figma.currentPage.children.find((n) => n.name === ${JSON.stringify(frameName)});
if (old) old.remove();
const node = figma.createNodeFromSvg(SVG);
node.name = ${JSON.stringify(frameName)};
const right = figma.currentPage.children.filter((n) => n !== node).reduce((m, n) => Math.max(m, n.x + n.width), 0);
node.x = right ? right + 120 : 0;
node.y = 0;
return { frameId: node.id, children: node.children.length, text: node.findAll((n) => n.type === 'TEXT').length, missingFonts: missing, createdNodeIds: [node.id], mutatedNodeIds: [] };
`;
	return script.length <= SCRIPT_LIMIT ? script : null;
}

/** Cleans an SVG for Figma: drops the XML prolog, comments, scripts and editor metadata; keeps ids as layer names. */
export function figmaSvg(svg: string): string {
	return svg
		.replace(/<\?xml[^>]*\?>/g, '')
		.replace(/<!DOCTYPE[^>]*>/gi, '')
		.replace(/<!--[\s\S]*?-->/g, '')
		.replace(/<script[\s\S]*?<\/script>/gi, '')
		.replace(/<metadata[\s\S]*?<\/metadata>/gi, '')
		.replace(/\s(?:sodipodi|inkscape):[\w-]+="[^"]*"/g, '')
		.trim();
}

/** Parses a Figma URL into the file key and node id the MCP tools take. */
export function parseFigmaUrl(url: string): { fileKey: string; nodeId?: string; kind: string } {
	const m = /figma\.com\/(design|file|board|slides|make|proto)\/([0-9a-zA-Z]{10,128})(?:\/[^?]*?)?(?:\/branch\/([0-9a-zA-Z]+))?(?:[/?].*)?$/.exec(url);
	if (!m) throw new Error(`Not a Figma file URL: ${url}. Expected https://figma.com/design/<fileKey>/<name>?node-id=1-2`);
	const branch = /\/branch\/([0-9a-zA-Z]+)/.exec(url)?.[1];
	const node = /[?&]node-id=([\d]+[-:][\d]+)/.exec(url)?.[1];
	return { fileKey: branch ?? m[2]!, ...(node ? { nodeId: node.replace('-', ':') } : {}), kind: m[1] === 'file' ? 'design' : m[1]! };
}
