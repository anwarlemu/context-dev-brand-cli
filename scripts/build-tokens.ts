type TokenNode = { $value?: unknown; $type?: string; $description?: string; [key: string]: unknown };

const ROOT = process.cwd();
const TOKEN_DIRS = ['tokens/primitive', 'tokens/semantic', 'tokens/component'];
const BUILD = join(ROOT, 'build');

function loadTree(): TokenNode {
	const tree: TokenNode = {};
	for (const dir of TOKEN_DIRS) {
		for (const file of readdirSync(join(ROOT, dir)).filter((f) => f.endsWith('.json'))) {
			deepMerge(tree, JSON.parse(readFileSync(join(ROOT, dir, file), 'utf8')));
		}
	}
	return tree;
}

function deepMerge(target: TokenNode, source: TokenNode) {
	for (const [key, value] of Object.entries(source)) {
		if (value && typeof value === 'object' && !Array.isArray(value) && !('$value' in (value as TokenNode))) {
			target[key] = target[key] ?? {};
			deepMerge(target[key] as TokenNode, value as TokenNode);
		} else {
			target[key] = value;
		}
	}
}

function lookup(tree: TokenNode, path: string): TokenNode {
	const node = path.split('.').reduce<unknown>((acc, part) => (acc as TokenNode)?.[part], tree) as TokenNode | undefined;
	if (!node || !('$value' in node)) throw new Error(`Unknown token reference {${path}}`);
	return node;
}

export function resolveValue(tree: TokenNode, value: unknown, seen: string[] = []): unknown {
	if (typeof value === 'string') {
		const whole = value.match(/^\{([^}]+)\}$/);
		if (whole) {
			if (seen.includes(whole[1])) throw new Error(`Circular reference ${[...seen, whole[1]].join(' -> ')}`);
			return resolveValue(tree, lookup(tree, whole[1]).$value, [...seen, whole[1]]);
		}
		return value;
	}
	if (value && typeof value === 'object' && !Array.isArray(value)) {
		return Object.fromEntries(Object.entries(value).map(([k, v]) => [k, resolveValue(tree, v, seen)]));
	}
	return value;
}

function luminance(hex: string) {
	const channels = hex.replace('#', '').match(/../g)!.map((h) => parseInt(h, 16) / 255);
	const [r, g, b] = channels.map((c) => (c <= 0.03928 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4));
	return 0.2126 * r + 0.7152 * g + 0.0722 * b;
}

export function contrastRatio(a: string, b: string) {
	const [hi, lo] = [luminance(a), luminance(b)].sort((x, y) => y - x);
	return (hi + 0.05) / (lo + 0.05);
}

function walk(node: TokenNode, path: string[], visit: (path: string[], token: TokenNode) => void) {
	if ('$value' in node) return visit(path, node);
	for (const [key, child] of Object.entries(node)) {
		if (!key.startsWith('$') && child && typeof child === 'object') walk(child as TokenNode, [...path, key], visit);
	}
}

